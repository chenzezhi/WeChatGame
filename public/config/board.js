'use strict';

/* ==================== 功能 ====================
 * 棋盘布局 —— 只放数据，代码负责把它画出来
 *
 * 一个字符 = 一个格子：
 *   A  空格子，可以放卡牌
 *   S  起点，人物站在这里
 *   .  空洞，不画格子（回字形中间的洞）
 *
 * 改棋盘形状只改 map：加一行、删一行、把 A 改成 . 都行。
 * ==============================================*/

/* ==================== 用法 ====================
 * const board = require('../config/board.js');
 *
 * board.map        // 布局，字符串数组
 * board.cellRatio  // 格子边长占画布宽度的比例
 * board.topRatio   // 棋盘纵向起点，占画布高度的比例
 * ==============================================*/

module.exports = {
  // 棋盘布局：每行长度要一样。空格只为看着清楚，解析时会忽略
  map: [
    'A A A A A',
    'A A A A A',
    'A A . A A',
    'A A A A A',
    'A A A A A',
  ],

  // 尺寸全部用比例，换任何分辨率的手机都不会错位
  cellRatio: 0.17,  // 格子边长占画布宽度的比例（5 格约 85% 宽）
  gapRatio: 0.012,  // 格子间距占画布宽度的比例
  topRatio: 0.4,    // 棋盘顶端位置，占画布高度的比例

  cellSprite: 30,   // 格子用的图集序号（图集里哪个小图当格子）
  startClip: 'nf1', // 起点上的人物动画名，取 assets.js 里 clips 的 key
};
