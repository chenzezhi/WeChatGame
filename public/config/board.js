'use strict';

/* ==================== 功能 ====================
 * 棋盘布局 —— 只放数据
 *
 * 一个字符 = 一个格子（改这里就能改棋盘形状）：
 *   A  空格子，可以放卡牌
 *   S  起点，人物从这里出发
 *   .  空洞，不画格子（回字形中间的洞）
 *
 * 读取它的是 public/core/board.js，这里不写任何逻辑。
 * ==============================================*/

/* ==================== 用法 ====================
 * const CONFIG = require('../config/board.js');
 * const board = new Board(CONFIG, { width: w, height: h, frame: frame });
 * ==============================================*/

module.exports = {
  // 布局：每行长度要一样。空格只为看着清楚，解析时会忽略
  map: [
    'A A A A A',
    'A A A A A',
    'A A . A A',
    'A A A A A',
    'A A A A A',
  ],

  // 尺寸全用比例，换任何分辨率的手机都不会错位
  cellRatio: 0.17,   // 格子边长占画布宽度的比例（5 格约 85% 宽）
  gapRatio: 0.012,   // 格子间距占画布宽度的比例
  topRatio: 0.2,     // 棋盘顶端位置，占画布高度的比例

  cellSprite: 30,    // 格子用的图集序号
};
