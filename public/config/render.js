'use strict';

/* ==================== 功能 ====================
 * 渲染配置默认值 —— 所有渲染器共用同一套字段
 *
 * 这里只放「默认值」，也就是完整数据模板。
 * 字段顺序不放在这里：字段头写在表格数据的第 0 行，
 * 一眼就能看到每列是什么（见 public/core/demo.js）。
 * ==============================================*/

/* ==================== 用法 ====================
 * const TEMPLATE = require('../config/render.js').template;
 * const list = TableMapper.fill(TEMPLATE, table);
 * ==============================================*/

/* ==================== 注意 ====================
 * renderer  : 'image' | 'sprite' | 'anim'   用哪个渲染器
 * name      : 图片路径 / 图集小图名字或序号 / 动画名
 * scale     : 大小倍数（1 = 原始尺寸）
 * right/bottom : 平铺区域右下角；写 0 表示不平铺，只放一张
 * ==============================================*/

module.exports = {
  // 完整数据模板：写数据时没写到的字段，就用这里的值
  template: {
    renderer: '',   // 用哪个渲染器
    name: '',       // 素材名字 / 路径
    x: 0,           // 左上角 x
    y: 0,           // 左上角 y
    scale: 1,       // 大小倍数
    gap: 0,         // 平铺时间距
    margin: 0,      // 平铺时四周留白
    right: 0,       // 平铺区域右下角 x（0 = 不平铺）
    bottom: 0,      // 平铺区域右下角 y（0 = 不平铺）
  },
};
